-- 3. 그룹 관리 시스템
-- ==========================================

CREATE TABLE IF NOT EXISTS adminax_groups (
    group_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name  TEXT NOT NULL,
    description TEXT,
    owner_id    BIGINT NOT NULL REFERENCES adminax_users(user_id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at  TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS adminax_group_members (
    group_id   BIGINT REFERENCES adminax_groups(group_id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES adminax_users(user_id) ON DELETE CASCADE,
    joined_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (group_id, user_id)
);

