-- 수정 시각 자동 업데이트 트리거 등록
DO $$ 
DECLARE 
    t text;
BEGIN
    FOR t IN SELECT table_name FROM information_schema.tables 
             WHERE table_name IN ('adminax_users', 'adminax_folder_mng', 'adminax_documents', 'adminax_chat_room', 'adminax_groups')
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_modtime ON %I', t, t);
        EXECUTE format('CREATE TRIGGER trg_%I_modtime BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION adminax_set_modified_at()', t, t);
    END LOOP;
END $$;

-- 검색 벡터 자동 갱신 트리거
CREATE OR REPLACE FUNCTION adminax_update_doc_search_vector()
RETURNS TRIGGER AS $$
BEGIN
  NEW.search_vector :=
    setweight(to_tsvector('simple', coalesce(NEW.doc_name, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(NEW.summary, '')), 'B') ||
    setweight(to_tsvector('simple', array_to_string(NEW.keywords, ' ')), 'B') ||
    setweight(to_tsvector('simple', coalesce(NEW.content, '')), 'C');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_adminax_doc_search_update ON adminax_documents;
CREATE TRIGGER trg_adminax_doc_search_update
BEFORE INSERT OR UPDATE OF doc_name, summary, keywords, content ON adminax_documents
FOR EACH ROW EXECUTE FUNCTION adminax_update_doc_search_vector();