-- 2. 유저 및 인증 시스템 (1:N)
-- ==========================================

-- 유저 메인 (Identity)
CREATE TABLE IF NOT EXISTS adminax_users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 표준 ID 생성 방식
    user_uuid     UUID DEFAULT gen_random_uuid() NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    full_name     TEXT NOT NULL,
    status        TEXT DEFAULT 'ACTIVE',
    is_admin      BOOLEAN DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    modified_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at    TIMESTAMPTZ NULL,
    CONSTRAINT adminax_user_status_chk CHECK (status IN ('ACTIVE', 'SLEEP', 'WITHDRAWN', 'GUEST'))
);

-- 계정 인증 (Authentication Accounts)
CREATE TABLE IF NOT EXISTS adminax_user_accounts (
    account_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES adminax_users(user_id) ON DELETE CASCADE,
    provider         TEXT NOT NULL, -- LOCAL, KAKAO, NAVER, GOOGLE
    provider_user_id TEXT NOT NULL, 
    password_hash    TEXT NULL,
    last_login_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ux_adminax_provider_id UNIQUE (provider, provider_user_id)
);

