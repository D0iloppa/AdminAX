-- 수정 시간 자동 업데이트 함수
CREATE OR REPLACE FUNCTION adminax_set_modified_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.modified_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

